function languageOf(req) {
    const header = (req.get('Accept-Language') || '').toLowerCase();
    return header.startsWith('es') ? 'es' : 'en';
}

function msg(req, key) {
    return MESSAGES[languageOf(req)][key] || MESSAGES.en[key] || key;
}

